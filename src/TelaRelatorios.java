    private void carregarRelatorio() {

    String sql =
            "SELECT t.data, t.descricao, c.nome, t.tipo, t.valor " +
            "FROM Transacao t " +
            "INNER JOIN Categoria c ON t.categoria_id = c.id " +
            "WHERE t.usuario_id = 1 " +
            "ORDER BY t.data";

    try (
        java.sql.Connection conexao = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conexao.prepareStatement(sql);
        java.sql.ResultSet resultado =
                stmt.executeQuery()
    ) {

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) tblRelatorios.getModel();

        modelo.setRowCount(0);

        double totalEntradas = 0;
        double totalDespesas = 0;

        while (resultado.next()) {

            java.sql.Date data =
                    resultado.getDate("data");

            String descricao =
                    resultado.getString("descricao");

            String categoria =
                    resultado.getString("nome");

            String tipo =
                    resultado.getString("tipo");

            double valor =
                    resultado.getDouble("valor");

            String dataFormatada =
                    new java.text.SimpleDateFormat("dd/MM/yyyy")
                    .format(data);

            modelo.addRow(new Object[]{
                dataFormatada,
                descricao,
                categoria,
                tipo,
                String.format("R$ %.2f", valor)
            });

            if (tipo.equals("Entrada")) {
                totalEntradas += valor;
            } else if (tipo.equals("Despesa")) {
                totalDespesas += valor;
            }
        }

        double saldo = totalEntradas - totalDespesas;

        lblValorEntradas.setText(
                String.format("R$ %.2f", totalEntradas)
        );

        lblValorDespesas.setText(
                String.format("R$ %.2f", totalDespesas)
        );

        lblValorSaldo.setText(
                String.format("R$ %.2f", saldo)
        );

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar o relatório:\n"
                + e.getMessage(),
                "Erro",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
    

