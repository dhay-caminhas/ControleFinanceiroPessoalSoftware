    private void chkMostrarValoresActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkMostrarValoresActionPerformed
                                                     
    if (chkMostrarValores.isSelected()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Os valores serão mostrados no Dashboard."
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Os valores serão ocultados no Dashboard."
        );
    }
    
    }//GEN-LAST:event_chkMostrarValoresActionPerformed

    private void chkConfirmarExclusaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkConfirmarExclusaoActionPerformed
        if (chkConfirmarExclusao.isSelected()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "A confirmação antes de excluir foi ativada."
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "A confirmação antes de excluir foi desativada."
        );
    }
    }//GEN-LAST:event_chkConfirmarExclusaoActionPerformed

    private void cmbCorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbCorActionPerformed
                                           
    String tema = cmbCor.getSelectedItem().toString();

    if (tema.equals("Claro")) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Tema Claro selecionado."
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Tema Escuro selecionado."
        );
    }
    
    }//GEN-LAST:event_cmbCorActionPerformed

    private void btnLimparDadosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparDadosActionPerformed
                                                    
    int resposta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Tem certeza que deseja limpar os dados?",
            "Confirmar",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (resposta == javax.swing.JOptionPane.YES_OPTION) {
        
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Os dados foram limpos com sucesso!"
        );
        
    }
    
    }//GEN-LAST:event_btnLimparDadosActionPerformed

    private void btnRestaurarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRestaurarActionPerformed
                                                   
    int resposta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Deseja restaurar as configurações padrão?",
            "Restaurar configurações",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (resposta == javax.swing.JOptionPane.YES_OPTION) {
        
        cmbCor.setSelectedItem("Claro");
        chkMostrarValores.setSelected(true);
        chkConfirmarExclusao.setSelected(true);

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Configurações restauradas com sucesso!"
        );
    }
    
    }//GEN-LAST:event_btnRestaurarActionPerformed


