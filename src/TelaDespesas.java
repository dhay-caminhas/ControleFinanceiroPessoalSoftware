    private void carregarDespesas() {

    String sql =
            "SELECT t.id, t.data, t.descricao, c.nome, t.valor " +
            "FROM Transacao t " +
            "INNER JOIN Categoria c ON t.categoria_id = c.id " +
            "WHERE t.tipo = 'Despesa' " +
            "AND t.usuario_id = 1 " +
            "ORDER BY t.data";

    try (
        java.sql.Connection conexao = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conexao.prepareStatement(sql);
        java.sql.ResultSet resultado =
                stmt.executeQuery()
    ) {

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel)
                tblDespesas.getModel();

        // Limpa as linhas atuais da tabela
        modelo.setRowCount(0);

        while (resultado.next()) {

            java.sql.Date data =
                    resultado.getDate("data");

            String dataFormatada =
                    new java.text.SimpleDateFormat("dd/MM/yyyy")
                    .format(data);

            String descricao =
                    resultado.getString("descricao");

            String categoria =
                    resultado.getString("nome");

            double valor =
                    resultado.getDouble("valor");

            modelo.addRow(new Object[]{
                    resultado.getInt("id"),
                    dataFormatada,
                    descricao,
                    categoria,
            String.format("R$ %.2f", valor)
            });
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao carregar as despesas:\n" + e.getMessage(),
            "Erro",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}

