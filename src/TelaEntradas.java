    private void btnAdicionarEntradaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarEntradaActionPerformed
                                                    
    String descricao = txtDescricao.getText().trim();
    String valorTexto = txtValor.getText().trim();
    String dataTexto = txtData.getText().trim();

    if (cmbCategoria.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(
                this,
                "Selecione uma categoria.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String categoria = cmbCategoria.getSelectedItem().toString();

    if (descricao.isEmpty() || valorTexto.isEmpty() || dataTexto.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    double valor = 0.0;

    try {
        valor = Double.parseDouble(valorTexto.replace(",", "."));

        if (valor <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Digite um valor maior que zero.",
                    "Atenção",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this,
                "Digite um valor válido.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    java.sql.Date dataSql;

    try {
        java.text.SimpleDateFormat formatoEntrada = new java.text.SimpleDateFormat("dd/MM/yyyy");
        formatoEntrada.setLenient(false);
        java.util.Date dataConvertida = formatoEntrada.parse(dataTexto);

        java.text.SimpleDateFormat formatoBanco = new java.text.SimpleDateFormat("yyyy-MM-dd");
        String dataBanco = formatoBanco.format(dataConvertida);
        
        dataSql = java.sql.Date.valueOf(dataBanco);

    } catch (java.text.ParseException e) {
        JOptionPane.showMessageDialog(
                this,
                "Digite a data no formato dd/MM/yyyy.\nExemplo: 13/09/2026",
                "Data inválida",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sqlCategoria =
            "SELECT id FROM Categoria WHERE nome = ? AND tipo = 'Entrada'";

    String sqlEntrada =
            "INSERT INTO Transacao "
            + "(usuario_id, categoria_id, valor, data, descricao, tipo) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    try (Connection conexao = Conexao.conectar()) {

        int idCategoria;

        try (PreparedStatement stmtCategoria =
                conexao.prepareStatement(sqlCategoria)) {

            stmtCategoria.setString(1, categoria);

            try (ResultSet resultado = stmtCategoria.executeQuery()) {

                if (!resultado.next()) {
                    JOptionPane.showMessageDialog(
                            this,
                            "A categoria selecionada não existe no banco de dados.",
                            "Erro",
                            JOptionPane.ERROR_MESSAGE
                    );
                    return;
                }

                idCategoria = resultado.getInt("id");
            }
        }

        try (PreparedStatement stmt =
                conexao.prepareStatement(sqlEntrada)) {

            stmt.setInt(1, 1);
            stmt.setInt(2, idCategoria);
            stmt.setDouble(3, valor);
            stmt.setDate(4, dataSql);
            stmt.setString(5, descricao);
            stmt.setString(6, "Entrada");

            stmt.executeUpdate();
        }

        JOptionPane.showMessageDialog(
                this,
                "Entrada salva no banco de dados com sucesso!"
        );

        txtDescricao.setText("");
        txtValor.setText("");
        txtData.setText("");
        
        // Atualiza a tabela na tela após adicionar
        carregarEntradas();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Erro ao salvar a entrada no banco de dados:\n"
                + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    }//GEN-LAST:event_btnAdicionarEntradaActionPerformed

