    private void carregarEntradas() {
    DefaultTableModel modelo = (DefaultTableModel) tblEntradas.getModel();
    modelo.setRowCount(0);

    String sql = "SELECT t.data, t.descricao, c.nome, t.valor "
            + "FROM Transacao t "
            + "INNER JOIN Categoria c ON t.categoria_id = c.id "
            + "WHERE t.usuario_id = 1 AND t.tipo = 'Entrada' "
            + "ORDER BY t.data";

    try (
        Connection conexao = Conexao.conectar();
        PreparedStatement stmt = conexao.prepareStatement(sql);
        ResultSet resultado = stmt.executeQuery()
    ) {
        while (resultado.next()) {
            java.sql.Date data = resultado.getDate("data");
            String dataFormatada = new java.text.SimpleDateFormat("dd/MM/yyyy").format(data);

            modelo.addRow(new Object[]{
                dataFormatada,
                resultado.getString("descricao"),
                resultado.getString("nome"),
                String.format("R$ %.2f", resultado.getDouble("valor"))
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar as entradas:\n" + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

