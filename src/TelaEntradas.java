    private void btnExcluirEntradaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirEntradaActionPerformed
        int linhaSelecionada = tblEntradas.getSelectedRow();

if (linhaSelecionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Selecione uma entrada para excluir.",
        "Atenção",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

int resposta = javax.swing.JOptionPane.showConfirmDialog(
    this,
    "Tem certeza que deseja excluir esta entrada?",
    "Confirmar exclusão",
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (resposta == javax.swing.JOptionPane.YES_OPTION) {

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblEntradas.getModel();

    modelo.removeRow(linhaSelecionada);

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Entrada excluída com sucesso!"
    );
} 
    }//GEN-LAST:event_btnExcluirEntradaActionPerformed


