    private void carregarPlanejamento() {

    String sql =
            "SELECT necessidades, desejos, poupanca, total " +
            "FROM Planejamento " +
            "WHERE usuario_id = 1 " +
            "ORDER BY id DESC " +
            "LIMIT 1";

    try (
        java.sql.Connection conexao = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conexao.prepareStatement(sql);
        java.sql.ResultSet resultado =
                stmt.executeQuery()
    ) {

        if (resultado.next()) {

            double necessidades =
                    resultado.getDouble("necessidades");

            double desejos =
                    resultado.getDouble("desejos");

            double poupanca =
                    resultado.getDouble("poupanca");

            double total =
                    resultado.getDouble("total");

            txtNecessidades.setText(
                    String.format("%.2f", necessidades)
            );

            txtDesejos.setText(
                    String.format("%.2f", desejos)
            );

            txtPoupanca.setText(
                    String.format("%.2f", poupanca)
            );

            lblValorTotal.setText(
                    String.format("R$ %.2f", total)
            );
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar o planejamento:\n"
                + e.getMessage(),
                "Erro",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}

