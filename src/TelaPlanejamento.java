    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
  
    String necessidadesTexto = txtNecessidades.getText().trim();
    String desejosTexto = txtDesejos.getText().trim();
    String poupancaTexto = txtPoupanca.getText().trim();

    if (necessidadesTexto.isEmpty()
            || desejosTexto.isEmpty()
            || poupancaTexto.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos.",
                "Atenção",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    try {

        double necessidades = Double.parseDouble(
                necessidadesTexto.replace(",", ".")
        );

        double desejos = Double.parseDouble(
                desejosTexto.replace(",", ".")
        );

        double poupanca = Double.parseDouble(
                poupancaTexto.replace(",", ".")
        );

        // Calcula o total
        double total = necessidades + desejos + poupanca;

        // Salva no banco de dados
        String sql =
                "INSERT INTO Planejamento " +
                "(necessidades, desejos, poupanca, total, usuario_id) " +
                "VALUES (?, ?, ?, ?, ?)";

        try (
            java.sql.Connection conexao = Conexao.conectar();
            java.sql.PreparedStatement stmt =
                    conexao.prepareStatement(sql)
        ) {

            stmt.setDouble(1, necessidades);
            stmt.setDouble(2, desejos);
            stmt.setDouble(3, poupanca);
            stmt.setDouble(4, total);
            stmt.setInt(5, 1);

            stmt.executeUpdate();

            // Mostra o total na tela
            lblValorTotal.setText(
                    String.format("R$ %.2f", total)
            );

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Planejamento salvo com sucesso!",
                    "Sucesso",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Digite apenas números válidos nos campos.",
                "Valor inválido",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao salvar o planejamento no banco:\n"
                + e.getMessage(),
                "Erro",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSalvarActionPerformed

