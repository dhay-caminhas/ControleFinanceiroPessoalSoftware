   private void carregarMetas() {

    String sql =
            "SELECT id, nome, valor_objetivo, valor_atual, data_limite " +
            "FROM Meta " +
            "WHERE usuario_id = 1 " +
            "ORDER BY id";

    try (
        java.sql.Connection conexao = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conexao.prepareStatement(sql);
        java.sql.ResultSet resultado =
                stmt.executeQuery()
    ) {

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) tabelaMetas.getModel();

        // Limpa a tabela antes de carregar os dados
        modelo.setRowCount(0);

        while (resultado.next()) {

            int id = resultado.getInt("id");

            String nome =
                    resultado.getString("nome");

            double valorObjetivo =
                    resultado.getDouble("valor_objetivo");

            double valorAtual =
                    resultado.getDouble("valor_atual");

            java.sql.Date data =
                    resultado.getDate("data_limite");

            String dataFormatada =
                    new java.text.SimpleDateFormat("dd/MM/yyyy")
                    .format(data);

            modelo.addRow(new Object[]{
                id,
                nome,
                String.format("R$ %.2f", valorObjetivo),
                String.format("R$ %.2f", valorAtual),
                dataFormatada
            });
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao carregar as metas:\n" + e.getMessage(),
            "Erro",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
        

