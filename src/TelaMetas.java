    private void btnExcluirMetaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirMetaActionPerformed
                                                                                              
    int linhaSelecionada = tabelaMetas.getSelectedRow();

    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecione uma meta para excluir.",
            "Atenção",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Pega o ID da meta selecionada
    int id = Integer.parseInt(
        tabelaMetas.getValueAt(linhaSelecionada, 0).toString()
    );

    int resposta = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Tem certeza que deseja excluir esta meta?",
        "Confirmar exclusão",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (resposta != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    String sql =
            "DELETE FROM Meta WHERE id = ?";

    try (
        java.sql.Connection conexao = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conexao.prepareStatement(sql)
    ) {

        stmt.setInt(1, id);

        int resultado = stmt.executeUpdate();

        if (resultado > 0) {

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Meta excluída com sucesso!"
            );

            // Recarrega a tabela diretamente do MySQL
            carregarMetas();
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao excluir a meta do banco:\n"
            + e.getMessage(),
            "Erro",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnExcluirMetaActionPerformed

    private void btnAdicionarMetaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarMetaActionPerformed
                                                      
   String nome = txtNomeMeta.getText().trim();
   String valorObjetivoTexto = txtValorObjetivo.getText().trim();
   String valorAtualTexto = txtValorAtual.getText().trim();
   String dataTexto = txtDataLimite.getText().trim();

  if (nome.isEmpty() || valorObjetivoTexto.isEmpty()
        || valorAtualTexto.isEmpty() || dataTexto.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Preencha todos os campos.",
        "Atenção",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );

    return;
  }

   try {

    double valorObjetivo = Double.parseDouble(
        valorObjetivoTexto.replace(",", ".")
    );

    double valorAtual = Double.parseDouble(
        valorAtualTexto.replace(",", ".")
    );

    java.text.SimpleDateFormat formatoEntrada =
            new java.text.SimpleDateFormat("dd/MM/yyyy");

    formatoEntrada.setLenient(false);

    java.util.Date dataConvertida =
            formatoEntrada.parse(dataTexto);

    java.text.SimpleDateFormat formatoBanco =
            new java.text.SimpleDateFormat("yyyy-MM-dd");

    String dataBanco = formatoBanco.format(dataConvertida);

    String sql =
            "INSERT INTO Meta " +
            "(nome, valor_objetivo, valor_atual, data_limite, usuario_id) " +
            "VALUES (?, ?, ?, ?, ?)";

    try (
        java.sql.Connection conexao = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conexao.prepareStatement(
                    sql,
                    java.sql.Statement.RETURN_GENERATED_KEYS
                )
    ) {

        stmt.setString(1, nome);
        stmt.setDouble(2, valorObjetivo);
        stmt.setDouble(3, valorAtual);
        stmt.setString(4, dataBanco);
        stmt.setInt(5, 1);

        stmt.executeUpdate();

        java.sql.ResultSet resultado =
                stmt.getGeneratedKeys();

        int id = 0;

        if (resultado.next()) {
            id = resultado.getInt(1);
        }

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel)
                tabelaMetas.getModel();

        modelo.addRow(new Object[]{
                id,
                nome,
                String.format("R$ %.2f", valorObjetivo),
                String.format("R$ %.2f", valorAtual),
                dataTexto
           });
    }

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Meta adicionada com sucesso!",
        "Sucesso",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

    txtNomeMeta.setText("");
    txtValorObjetivo.setText("");
    txtValorAtual.setText("");
    txtDataLimite.setText("");

    } catch (java.text.ParseException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Digite a data no formato dd/MM/yyyy.",
        "Data inválida",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );

    } catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Digite valores numéricos válidos.",
        "Valor inválido",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );

    } catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Erro ao cadastrar a meta no banco:\n"
        + e.getMessage(),
        "Erro",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
    }

    }//GEN-LAST:event_btnAdicionarMetaActionPerformed

